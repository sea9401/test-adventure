export type ChapterCompletionRule =
  | { kind: "storyFlag"; flagId: string }
  | { kind: "questCompleted"; questId: string }
  | { kind: "regionVisited"; regionId: RegionId }
  | { kind: "allOf"; rules: readonly ChapterCompletionRule[] }
